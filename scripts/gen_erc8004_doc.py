"""Write docs/agent/erc8004-card.md from tokenURI(agentId) on Celo.

The card is marketing a judge reads first, so the file that mirrors it must not be
hand-maintained: it said "1,637 chars, services added later" long after both were
false. This regenerates it, and a test fails if the committed copy drifts.

    .venv/bin/python scripts/gen_erc8004_doc.py
"""

from __future__ import annotations

import base64
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from dotenv import load_dotenv  # noqa: E402

from bot import chain  # noqa: E402

load_dotenv(os.path.join(ROOT, ".env"))

REGISTRY = "0x8004A169FB4a3325136EB29fA0ceB6D2e539a432"
AGENT_ID = int(os.environ.get("ERC8004_AGENT_ID", "10005"))
OUT = os.path.join(ROOT, "docs", "agent", "erc8004-card.md")

ABI = [{"name": "tokenURI", "type": "function", "stateMutability": "view",
        "inputs": [{"name": "tokenId", "type": "uint256"}],
        "outputs": [{"name": "", "type": "string"}]}]


def read_uri() -> str:
    from web3 import Web3
    w3 = chain.w3()
    contract = w3.eth.contract(address=Web3.to_checksum_address(REGISTRY), abi=ABI)
    for _ in range(6):
        try:
            return contract.functions.tokenURI(AGENT_ID).call()
        except Exception:  # noqa: BLE001 — load-balanced nodes read a block behind
            import time
            time.sleep(3)
    raise SystemExit("could not read tokenURI")


def render(uri: str) -> str:
    meta = json.loads(base64.b64decode(uri.split(",", 1)[1]))
    lines = [
        "# ERC-8004 card (generated)",
        "",
        "Do not edit this file. It is written by `scripts/gen_erc8004_doc.py`, which",
        f"reads `tokenURI({AGENT_ID})` from `{REGISTRY}` on Celo mainnet:",
        "",
        "```bash",
        ".venv/bin/python scripts/gen_erc8004_doc.py",
        "```",
        "",
        f"`agentURI` length onchain: **{len(uri)} chars** (`data:application/json;base64,…`).",
        "",
        "| field | value |",
        "|---|---|",
        f"| name | {meta.get('name')} |",
        f"| active | {json.dumps(meta.get('active'))} |",
        f"| x402Support | {json.dumps(meta.get('x402Support'))} |",
    ]
    for i, svc in enumerate(meta.get("services") or []):
        lines.append(f"| services[{i}] | `{svc.get('name')}` → {svc.get('endpoint')} |")
    for i, reg in enumerate(meta.get("registrations") or []):
        lines.append(f"| registrations[{i}] | agentId {reg.get('agentId')} · `{reg.get('agentRegistry')}` |")
    lines += [
        "",
        "## description",
        "",
        f"> {meta.get('description')}",
        "",
        "## full metadata",
        "",
        "```json",
        json.dumps(meta, indent=2, sort_keys=True),
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    uri = read_uri()
    text = render(uri)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if os.path.exists(OUT) and open(OUT).read() == text:
        print("docs/agent/erc8004-card.md already matches the chain")
        return 0
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote docs/agent/erc8004-card.md from tokenURI({AGENT_ID}) — {len(uri)} chars")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
